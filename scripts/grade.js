/* =========================================================================
   등급 — S · A · B · C 기준 하나 (2026-10-16)
   - 결과 화면 6장과 학습 기록이 같이 부른다. 기준을 화면 JS에 새로 쓰지 않는다
   - 95점 이상 S · 85점 이상 A · 70점 이상 B · 그 아래 C
     (현안 서비스에서 83점 = B를 확인했다 — 그래서 A는 85부터)
   ========================================================================= */
(function () {
  'use strict';
  window.RMGrade = {
    of: function (r) { return r >= 95 ? 's' : r >= 85 ? 'a' : r >= 70 ? 'b' : 'c'; }
  };
})();
